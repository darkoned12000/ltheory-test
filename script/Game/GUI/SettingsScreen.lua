--[[ SettingsScreen -- the SETTINGS page on the main menu.

  WHAT IT DECIDES AND WHAT IT ONLY CHANGES
  ========================================
  The screen edits LIVE values and persists them; it is not the place where
  Config's secrets live:

  WINDOW MODE / RESOLUTION apply straight to the `Window` on the spot, and
  the saved file (script/Config.Settings.lua) remembers them for the next
  boot. The engine picks that up twice: at boot via `getDefaultSize`
  (the window opens at the monitor's own size, unless the player picked an
  explicit resolution, in which case `autoSize` is false and the picked
  width/height is used), and every frame via Application's resize check --
  so a live change re-lays the WHOLE UI on the next frame, with no special
  code here.

  VOLUMES write two numbers: `Config.audio.musicVolume` (applied live to
  the music voice) and `Config.audio.sfxVolume` (a master gain the SFX
  sites multiply in when they play; the engine loop sound re-reads it every
  frame, so its gain follows the slider while the ship keeps thrusting).

  THE SETTINGS FILE is written with the engine's File API, not `io.*` --
  the app runs under GlobalRestrict and io may be restricted. The file is
  plain Lua, applied in Main.lua after Config.Local.lua, and deleting it
  is the "reset to boot defaults" button.

  THE WIDGETS are the framework's: `OptionSlider` cycles a list,
  `Slider` drags a gain, and both are driven by getFn/setFn closures --
  the getters are consulted EVERY frame, so what the row shows stays true
  even if something else changed the setting while the page was open.
]]

local ScrollView = require('UI.ScrollView')
local Screen     = require('Game.GUI.Screen')
local MenuPanelScreen = require('Game.GUI.MenuPanelScreen')
local Grid       = require('UI.Grid')
local Label      = require('UI.Label')
local OptionSlider = require('UI.OptionSlider')
local Slider     = require('UI.Slider')
local Displays   = require('phx.util.Displays')
local File       = require('ffi.File')

local SettingsScreen = {}
SettingsScreen.__index = SettingsScreen
setmetatable(SettingsScreen, MenuPanelScreen)

SettingsScreen.name = 'Settings Screen'

-- The file the settings persist to: relative to the app's working
-- directory (the repo root -- the same place Main.lua dofile's it from).
local SETTINGS_FILE = './script/Config.Settings.lua'

-- Gains formatted as plain Lua: 0.75, not 0.74999.
local function fmt (value)
  return string.format('%.4g', value)
end

-- ---------------------------------------------------------------------------
-- Persistence
-- ---------------------------------------------------------------------------

-- Rewrite the settings file from the CURRENT Config values. Every change
-- goes through `commit()`, so the file is the single source of truth for
-- "what did the player pick" and nothing else has to remember.
local function commit ()
  local ok, err = pcall(function ()
    local f = File.Create(SETTINGS_FILE)
    f:writeStr '-- GENERATED by the SETTINGS screen (Game/GUI/SettingsScreen.lua).\n'
    f:writeStr '-- Applied on boot in Main.lua, after Config.Local.lua. Edit or delete\n'
    f:writeStr '-- this file freely: deleting it restores the boot defaults.\n'
    if Config.window.autoSize == false then
      f:writeStr(string.format('Config.window.autoSize    = false\n'))
      f:writeStr(string.format('Config.window.width       = %d\n', Config.window.width))
      f:writeStr(string.format('Config.window.height      = %d\n', Config.window.height))
    end
    f:writeStr(string.format('Config.window.fullscreen  = %s\n', tostring(Config.window.fullscreen)))
    f:writeStr(string.format('Config.audio.musicVolume  = %s\n', fmt(Config.audio.musicVolume)))
    f:writeStr(string.format('Config.audio.sfxVolume    = %s\n', fmt(Config.audio.sfxVolume)))
    f:writeStr('-- Graphics (advanced)\n')
    f:writeStr(string.format('Config.gpu.bloom            = %s\n', tostring(Config.gpu.bloom)))
    f:writeStr(string.format('Config.gpu.bloomIntensity   = %s\n', fmt(Config.gpu.bloomIntensity)))
    f:writeStr(string.format('Config.gpu.sharpen          = %s\n', tostring(Config.gpu.sharpen)))
    f:writeStr(string.format('Config.gpu.sharpenStrength  = %s\n', fmt(Config.gpu.sharpenStrength)))
    f:writeStr(string.format('Config.gpu.tonemap          = %s\n', tostring(Config.gpu.tonemap)))
    f:writeStr(string.format('Config.gpu.exposureEV       = %s\n', fmt(Config.gpu.exposureEV)))
    f:writeStr(string.format('Config.gpu.colorSat         = %s\n', fmt(Config.gpu.colorSat)))
    f:writeStr(string.format('Config.gpu.colorContrast    = %s\n', fmt(Config.gpu.colorContrast)))
    f:writeStr(string.format('Config.gpu.colorTemp        = %s\n', fmt(Config.gpu.colorTemp)))
    f:writeStr(string.format('Config.gpu.colorTint        = %s\n', fmt(Config.gpu.colorTint)))
    f:close()
  end)
  if not ok then
    Log.Warning('SETTINGS: could not write %s (%s)', SETTINGS_FILE, tostring(err))
  end
end

-- ---------------------------------------------------------------------------
-- Row builders
-- ---------------------------------------------------------------------------

-- One setting row: a label on the left, the control on the right, in a
-- 3-column grid: [label][control][trailing]. THE LABEL COLUMN IS FIXED
-- WIDTH: each row is its own grid, and a label-sized first column makes
-- every row's control start wherever that row's label ends -- visible in
-- the wild as the music and effects sliders refusing to line up. 160px
-- covers the widest label here at the UI font's usual scale.
-- The control likewise gets a FIXED width, so every row's control ends at
-- the same x. A row without a value readout still adds the third column
-- (empty), so the control column lines up across ALL the rows.
local CONTROL_WIDTH = 280
local LABEL_WIDTH   = 220

local function buildRow (label, control, trailing)
  local row = Grid():setCols(3):setStretch(0, 0)
  row:setPadCellX(32)
  label:setWidth(LABEL_WIDTH)
  label:setStretch(0, 0)
  control:setStretch(1, 0)
  control:setWidth(CONTROL_WIDTH)
  control:setAlign(0, 0.5)
  -- NOTE : an empty label is `''`, not nil -- Label.Create stringifies its
  -- text, and `Label()` would draw the string "nil" in the third column.
  row:add(label):add(control):add(trailing or Label(''))
  return row
end

-- ---------------------------------------------------------------------------
-- The screen
-- ---------------------------------------------------------------------------

function SettingsScreen.Create (opts)
  opts = opts or {}
  local self = setmetatable({}, SettingsScreen)

  -- Copy the caller's opts and layer the defaults, exactly like every
  -- other screen does -- Screen.init keeps every option it is given, and
  -- a constructor that rebuilt the table field by field is how menu
  -- buttons once lost their callbacks (see MainMenu.Create).
  local o = {}
  for k, v in pairs(opts) do o[k] = v end
  o.title    = o.title or 'SETTINGS'
  o.subtitle = o.subtitle or ''
  o.bandAtTop = true
  -- OPAQUE over the menu, like every other page (see MenuPanelScreen).
  o.backdrop = o.backdrop or Color(0.012, 0.016, 0.03, 1.0)

  Screen.init(self, o)
  -- Same page shape as a popup: content sizes to itself, CLOSE under it.
  self.content:setAlign(0.5, 0)
  self.content:setStretch(0, 0)

  local window   = o.window
  local gameView = o.gameView

  -- What the monitor can do, asked ONCE when the screen is built. A
  -- settings page does not need to re-enumerate display modes per frame;
  -- if the player plugs in a different monitor, closing and reopening
  -- CONFIG refreshes the list.
  local modes              = Displays.Modes()
  local desktopW, desktopH = Displays.Desktop()

  -- Resolution choices: the TALLEST 12, so the cycle stays small enough to
  -- find things in. Sorted by height (Displays.Modes sorts ascending), the
  -- tallest are the ones a game window wants; the monitor's own
  -- resolution is among them (SDL lists the desktop mode as a fullscreen
  -- mode), and that IS the boot default.
  local REAS  = {}
  local elems = {}
  do
    local first = max(1, #modes - 11)
    for i = first, #modes do
      local m = modes[i]
      REAS[#REAS + 1] = { w = m.w, h = m.h }
      elems[#elems + 1] = string.format('%dx%d', m.w, m.h)
    end
  end

  local function currentResIndex ()
    -- What resolution is IN EFFECT right now: autoSize means "the
    -- monitor's own", otherwise whatever was picked (and persisted)
    -- before. Compared NUMERICALLY -- the display numbers were once FFI
    -- int32s, and cdata values leak surprises through string keys.
    local w, h
    if Config.window.autoSize == false then
      w, h = Config.window.width, Config.window.height
    else
      w, h = desktopW, desktopH
    end
    if w and h then
      for i = 1, #REAS do
        if REAS[i].w == w and REAS[i].h == h then return i end
      end
    end
    return nil
  end

  local resIdx = currentResIndex() or 1

  local function applyResolution (i)
    local m = REAS[i]
    if not m or (window == nil) then return end
    resIdx = i
    -- The picked resolution is now EXPLICIT: it persists as width/height
    -- (`autoSize` off) and applies to the window right now. While
    -- fullscreen, drop OUT and back IN:	SDL chooses the fullscreen mode
    -- from the window's size, so the size has to be set while the window
    -- is a plain compositor-window again.
    local wantsFullscreen = Config.window.fullscreen
    if wantsFullscreen then window:setFullscreen(false) end
    window:setSize(m.w, m.h)
    if wantsFullscreen then window:setFullscreen(true) end
    Config.window.autoSize = false
    Config.window.width    = m.w
    Config.window.height   = m.h
    commit()
  end

  local function applyMode (i)
    local wantsFullscreen = (i == 2)
    if wantsFullscreen ~= Config.window.fullscreen then
      Config.window.fullscreen = wantsFullscreen
      -- Going fullscreen keeps the window's size: SDL picks the mode
      -- closest to it. Coming back to windowed, the window re-appears at
      -- that same size -- both adopted by Application's resize check.
      if window then window:setFullscreen(wantsFullscreen) end
      commit()
    end
  end

  local modeSlide = OptionSlider.Create(
    function () return Config.window.fullscreen and 2 or 1 end,
    applyMode,
    { 'WINDOWED', 'FULLSCREEN' })

  local resSlide = OptionSlider.Create(
    function ()
      -- Read the CONFIG, not the window: mid-resize the window reports
      -- the compositor's size, and the selection would drift while the
      -- window is still settling on the picked mode.
      return currentResIndex() or resIdx
    end,
    applyResolution,
    elems)

  -- Volume sliders. Music is live (one call on the voice); the SFX gain
  -- lives in Config and is read by every playing sound -- nothing to
  -- enumerate here.
  local musicSlide = Slider.Create(
    function () return Config.audio.musicVolume end,
    function (v)
      Config.audio.musicVolume = Math.Clamp(v, 0, 1)
      if gameView and gameView.music then gameView.music:setVolume(Config.audio.musicVolume) end
      commit()
    end)

  local sfxSlide = Slider.Create(
    function () return Config.audio.sfxVolume end,
    function (v)
      Config.audio.sfxVolume = Math.Clamp(v, 0, 1)
      commit()
    end)

  -- THE FORM. Section headers, then label/control rows left-stacked in a
  -- column. The block sits slightly left of centre: it is a form, not a
  -- poster -- and it reads with the label column as the page's "spine",
  -- the way a settings list is usually laid out.
  -- The form is wrapped in a SCROLL VIEW so the page grows as settings
  -- are added (graphics + controls + future sections) without overflowing
  -- the window. The scroll view's height is capped to the window so the
  -- close button stays visible below it.
  local body = Grid():setCols(1):setAlign(0.5, 0)
  body:setStretch(0, 0)
  local function line (text, color)
    local l = Label():setText(text)
    if color then l:setFontColor(color) end
    body:add(l)
  end
  line('')
  line('')
  line('')
  line('')
  line('')
  line('DISPLAY', Color(0.45, 0.80, 1.0, 1.0))
  body:add(buildRow(Label('Window mode'), modeSlide))
  body:add(buildRow(Label('Resolution'), resSlide))
  line('')
  line('')
  line('')
  line('')
  line('')

  line('GRAPHICS (advanced)', Color(0.45, 0.80, 1.0, 1.0))
  -- Toggles via OptionSlider; sliders for continuous values.
  local bloomToggle = OptionSlider.Create(
    function () return Config.gpu.bloom and 2 or 1 end,
    function (i) Config.gpu.bloom = (i == 2); commit() end,
    { 'OFF', 'ON' })
  local bloomInt = Slider.Create(
    function () return Config.gpu.bloomIntensity end,
    function (v) Config.gpu.bloomIntensity = Math.Clamp(v, 0, 4); commit() end,
    0, 4)
  local sharpenToggle = OptionSlider.Create(
    function () return Config.gpu.sharpen and 2 or 1 end,
    function (i) Config.gpu.sharpen = (i == 2); commit() end,
    { 'OFF', 'ON' })
  local sharpenStr = Slider.Create(
    function () return Config.gpu.sharpenStrength end,
    function (v) Config.gpu.sharpenStrength = Math.Clamp(v, 0, 3); commit() end,
    0, 3)
  local tonemapToggle = OptionSlider.Create(
    function () return Config.gpu.tonemap and 2 or 1 end,
    function (i) Config.gpu.tonemap = (i == 2); commit() end,
    { 'OFF', 'ON' })
  local exposureSlide = Slider.Create(
    function () return (Config.gpu.exposureEV + 4) / 8 end,
    function (v) Config.gpu.exposureEV = Math.Clamp(v * 8 - 4, -4, 4); commit() end,
    0, 1)
  local satSlide = Slider.Create(
    function () return Config.gpu.colorSat / 3 end,
    function (v) Config.gpu.colorSat = Math.Clamp(v * 3, 0, 3); commit() end,
    0, 1)
  local contrastSlide = Slider.Create(
    function () return Config.gpu.colorContrast / 3 end,
    function (v) Config.gpu.colorContrast = Math.Clamp(v * 3, 0, 3); commit() end,
    0, 1)
  body:add(buildRow(Label('Bloom'), bloomToggle))
  body:add(buildRow(Label('Bloom intensity'), bloomInt))
  body:add(buildRow(Label('Sharpen'), sharpenToggle))
  body:add(buildRow(Label('Sharpen strength'), sharpenStr))
  body:add(buildRow(Label('Tonemap (HDR)'), tonemapToggle))
  body:add(buildRow(Label('Exposure (EV)'), exposureSlide))
  body:add(buildRow(Label('Saturation'), satSlide))
  body:add(buildRow(Label('Contrast'), contrastSlide))

  line('')
  line('')
  line('')
  line('')
  line('')
  line('AUDIO', Color(0.45, 0.80, 1.0, 1.0))
  body:add(buildRow(Label('Music volume'), musicSlide))
  body:add(buildRow(Label('Effects volume'),
    sfxSlide,
    Label():setMinWidth(60):setAlign(1, 0.5):setFormat('%.f%%')
      :setPollFn(function () return Math.Round(Config.audio.sfxVolume * 100) end)))

  line('')
  line('')
  line('')
  line('')
  line('')
  line('CONTROLS', Color(0.45, 0.80, 1.0, 1.0))
  body:add(buildRow(Label('Thrust'), Label('WASD')))
  body:add(buildRow(Label('Aim'), Label('Mouse (hold Space)')))
  body:add(buildRow(Label('Boost'), Label('LShift')))
  body:add(buildRow(Label('Fire'), Label('LMB')))
  body:add(buildRow(Label('Dock'), Label('F')))
  body:add(buildRow(Label('Target'), Label('T / G')))
  body:add(buildRow(Label('Map'), Label('V / F10')))
  body:add(buildRow(Label('Menu'), Label('Esc')))
  body:add(buildRow(Label('Quicksave'), Label('F6')))
  body:add(buildRow(Label('Quickload'), Label('F7')))
  line('')
  line('')
  line('')
  line('')
  line('')
  body:add(Label('Keybinding remapping is not yet available;')
    :setFontColor(Color(0.45, 0.80, 1.0, 1.0)))
  body:add(Label('both keyboard+mouse and gamepad are always active.')
    :setFontColor(Color(0.45, 0.80, 1.0, 1.0)))

  line('')
  line('')
  line('')
  line('')
  line('')
  line('Changes apply right away.', Color(0.45, 0.80, 1.0, 1.0))
  self:addCloseButton()


  local scrollView = ScrollView()
    :setPad(2, 24, 2, 2)
    :setScrollable(false, true)
    :add(body)
  if scrollView.setScrollSpeed then scrollView:setScrollSpeed(36) end
  if scrollView.setStretchY then scrollView:setStretchY(1) end
  self.content:setStretch(0, 1)
  self.content:add(scrollView)

  self.content:setAlign(0.44, 0.05)

  return self
end

return SettingsScreen
