#!/usr/bin/env python3
"""Write the game's version file.

THE VERSION IS THE COMMIT COUNT.

The project has no release numbering, and a version number is one more
thing somebody has to remember to bump. A number that changes every time
something is committed cannot go stale.

Writes a small Lua module the app reads at boot:

    return { count = 160, version = 'v0.160' }

Usage:  gen_version.py <output.lua>
"""

import os
import pathlib
import subprocess
import sys


def commit_count(root):
    try:
        out = subprocess.run(
            ['git', 'rev-list', '--count', 'HEAD'],
            cwd=root, capture_output=True, text=True, check=True)
        n = out.stdout.strip()
        return n if n.isdigit() else '0'
    except Exception:
        # No git, a fresh tarball, a shallow clone: the game still runs, it
        # just says it does not know.
        return '0'


def main():
    if len(sys.argv) < 2:
        print('usage: gen_version.py <output.lua>', file=sys.stderr)
        return 1

    out = pathlib.Path(sys.argv[1])
    root = os.path.dirname(os.path.dirname(os.path.abspath(out)))
    n = commit_count(root)

    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(
        "-- GENERATED by tools/gen_version.py -- do not edit.\n"
        "-- The version IS the number of commits.\n"
        "return { count = %s, version = 'v0.%s' }\n" % (n, n))
    print('version: v0.%s' % n)
    return 0


if __name__ == '__main__':
    sys.exit(main())
